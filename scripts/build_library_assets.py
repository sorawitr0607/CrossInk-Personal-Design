"""Bake the Library's SVG illustrations into flash-only, transparent 1-bit sprites.

Host build dependency: resvg-py==0.5.0, Pillow==13.0.0 and Node. Device code only
draws two packed masks; no SVG parser, runtime resize or second framebuffer.
"""
from __future__ import annotations

import hashlib
import io
import json
from pathlib import Path
import subprocess
import sys

from PIL import Image
import resvg_py

try:
    ROOT = Path(__file__).resolve().parents[1]
except NameError:  # PlatformIO executes extra scripts without __file__.
    Import("env")
    ROOT = Path(env.subst("$PROJECT_DIR"))
OUTPUT = ROOT / "src/activities/library/LibraryShelfAssets.generated.h"
FONT = ROOT / "lib/EpdFont/scalableFonts/bitter_regular.ttf"
BAYER = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def generate_fonts():
    converter = ROOT / "lib/EpdFont/scripts/fontconvert.py"
    italic = ROOT / "lib/EpdFont/scalableFonts/bitter_italic.ttf"
    output = ROOT / "src/activities/library/LibraryFonts.generated.h"
    digest = hashlib.sha256(converter.read_bytes() + FONT.read_bytes() + italic.read_bytes()
                            + (ROOT / "scripts/build_library_assets.py").read_bytes()).hexdigest()
    if output.exists() and digest in output.read_text(encoding="utf-8")[:160]:
        return
    parts = [f"// Generated Library bitmap fonts; source SHA256 {digest}\n"]
    for name, points, source in (("small", 6, FONT), ("body", 8, FONT), ("heading", 12, italic)):
        command = [sys.executable, str(converter), f"library_{name}", str(points), str(source),
                   "--no-default-intervals"]
        for interval in ("0x20,0x24f", "0x300,0x52f", "0x1ea0,0x1eff", "0x2000,0x206f", "0x20a0,0x20cf", "0xfffd,0xfffd"):
            command += ["--additional-intervals", interval]
        result = subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, encoding="utf-8")
        if result.returncode:
            raise RuntimeError(f"Library {name} font generation failed: {result.stderr[-1000:]}")
        parts.append(result.stdout)
    output.write_text("\n".join(parts), encoding="utf-8")
    print("Library labels: three flash-only bitmap sizes; no scalable font workspace")


def generate():
    sources = [ROOT / "scripts/build_library_assets.py", ROOT / "scripts/export_library_assets.cjs", FONT]
    sources += sorted((ROOT / "assets/library").rglob("*.js"))
    digest = hashlib.sha256(b"".join(p.read_bytes() for p in sources)).hexdigest()
    if OUTPUT.exists() and digest in OUTPUT.read_text(encoding="utf-8")[:160]:
        return
    data = json.loads(subprocess.check_output(["node", str(ROOT / "scripts/export_library_assets.cjs")]))
    lines = [f"// Generated by build_library_assets.py; source SHA256 {digest}",
             "#pragma once", '#include "LibraryShelfArt.h"', "namespace library_shelf { namespace assets {"]
    total = 0
    cache = {}

    def masks(im):
        white = Image.new("1", im.size, 1)
        black = Image.new("1", im.size, 1)
        for y in range(im.height):
            for x in range(im.width):
                r, g, b, a = im.getpixel((x, y))
                threshold = (BAYER[y % 4][x % 4] + 0.5) * 16
                if a <= threshold:
                    continue
                lum = (r * 299 + g * 587 + b * 114) // 1000
                lum = 255 if lum > 235 else 0 if lum < 40 else lum
                # Allocate black, white and transparent coverage in disjoint
                # intervals. Reusing the alpha threshold for gray intensity
                # otherwise erases thin gray SVG strokes completely.
                (black if threshold < a * (255 - lum) / 255 else white).putpixel((x, y), 0)
        # GfxRenderer::drawIcon consumes columns in reverse order in portrait.
        return [plane.transpose(Image.Transpose.ROTATE_90).tobytes() for plane in (white, black)]

    def sprite(name, image, at=0):
        nonlocal total
        pointers = []
        for label, packed in zip(("white", "black"), masks(image)):
            if all(byte == 255 for byte in packed):
                pointers.append("nullptr")
                continue
            if packed not in cache:
                symbol = f"{name}_{label}"
                lines.append(f"static const uint8_t {symbol}[] = {{")
                for start in range(0, len(packed), 24):
                    lines.append(",".join(f"0x{x:02x}" for x in packed[start:start + 24]) + ",")
                lines.append("};")
                cache[packed] = symbol
                total += len(packed)
            pointers.append(cache[packed])
        lines.append(f"static const Sprite {name} = {{{image.width},{image.height},{at},{pointers[0]},{pointers[1]}}};")
        return name

    themes = []
    for theme in data["themes"]:
        name = theme["id"].replace("-", "_")
        defs = data["defs"] + theme["defs"]

        def raster(w, h, inner, maxw=None, maxh=None, viewbox=None):
            scale = min(1, (maxw or w) / w, (maxh or h) / h)
            ow, oh = max(1, round(w * scale)), max(1, round(h * scale))
            svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="{ow}" height="{oh}" viewBox="{viewbox or f"0 0 {w} {h}"}"><defs>{defs}</defs>{inner}</svg>'
            png = resvg_py.svg_to_bytes(svg_string=svg, skip_system_fonts=True,
                                        font_files=[str(FONT)], font_family="Bitter")
            return Image.open(io.BytesIO(png)).convert("RGBA")

        wall = theme["wall"]["tile"]
        quiet = theme["wall"].get("quiet", wall)
        wall_name = sprite(name + "_wall", raster(wall["w"], wall["h"], wall["svg"], 120, 120))
        quiet_name = sprite(name + "_quiet", raster(quiet["w"], quiet["h"], quiet["svg"], 120, 120))
        hero = theme["hero"]
        hero_name = sprite(name + "_hero", raster(hero["w"], hero["h"], hero["svg"], 138, 74))
        plate_name = sprite(name + "_plate", raster(180, 54, theme["plate"]))
        all_name = sprite(name + "_all", raster(440, 60, theme["all"]))
        planks = []
        for layer in ("back", "front"):
            plank = raster(476, theme["plankHeight"] + 64, theme[layer], viewbox=f'-8 -25 476 {theme["plankHeight"] + 64}')
            parts = (("left", (0, 0, 20, plank.height)), ("mid", (20, 0, 84, plank.height)),
                     ("right", (456, 0, 476, plank.height)))
            for suffix, box in parts:
                planks.append(sprite(f"{name}_{layer}_{suffix}", plank.crop(box)))
        pieces = []
        for i, ornament in enumerate(theme["ornaments"]):
            at = {"shelf": 0, "wall": 1, "hang": 2, "perch": 3}[ornament["at"]]
            for size, mw, mh in (("normal", 88, 90), ("small", 48, 50)):
                pieces.append(sprite(f"{name}_piece_{i}_{size}", raster(ornament["w"], ornament["h"], ornament["svg"], mw, mh), at))
        lines.append(f'static const Sprite* const {name}_pieces[] = {{{",".join("&" + n for n in pieces)}}};')
        themes.append("{" + ",".join("&" + n for n in [wall_name, quiet_name, hero_name, plate_name, all_name] + planks)
                      + f",{name}_pieces,{len(pieces)}" + "}")
    lines.append("static const ThemeArt THEMES[] = {" + ",\n".join(themes) + "};")
    lines.append(f"static constexpr unsigned PACKED_BYTES = {total};")
    lines.append("} } // namespace library_shelf::assets\n")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Library artwork: {total:,} flash bytes, five themes, no runtime allocation")


generate_fonts()
generate()
